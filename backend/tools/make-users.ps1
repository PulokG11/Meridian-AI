# Generates one synthetic test user per seeded role (<role_key>@meridian.test), all sharing one
# randomly generated password. Writes the password to backend/seed/test-users.local.md (git-ignored,
# *.local.md in backend/.gitignore) and writes the SQL that creates each auth.users + auth.identities
# row (bcrypt via crypt($pw, gen_salt('bf'))) and the matching app.app_user row to
# backend/seed/011_test_users.generated.sql (git-ignored, *.generated.sql). Never prints the password.
#
# Usage: powershell -File backend/tools/make-users.ps1
# This script only writes files; it does not connect to the database. Apply the generated SQL
# separately (e.g. via the Supabase execute_sql tool).

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
$seedDir = Join-Path $repoRoot 'backend\seed'

# role_key -> portal (must match backend/seed/010_reference.sql's role list exactly)
$roles = [ordered]@{
  denials='provider'; appeals='provider'; billing='provider'; ar='provider'; cash='provider'; fin='provider';
  sup='provider'; mgr='provider'; comp='provider';
  contact='provider'; sched='provider'; reg='provider'; ver='provider'; auth='provider'; fc='provider'; am='provider';
  md='provider'; ma='provider'; ur='provider'; cdi='provider'; coder='provider'; him='provider'; enr='provider'; ri='provider'; tpl='provider';
  cua='provider'; pfs='provider'; ref='provider';
  cfo='provider'; priv='provider'; adm='provider';
  pat='patient'; gua='patient'; slf='patient';
  py1='payer'; py2='payer'; py3='payer'; py4='payer'; py5='payer'; py6='payer'; py7='payer'; py8='payer';
  ch1='clearinghouse'; ch2='clearinghouse'; ch3='clearinghouse';
  pl1='platform'; pl2='platform'; pl3='platform'
}

function New-RandomPassword([int]$length = 24) {
  $bytes = New-Object byte[] $length
  [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
  return [Convert]::ToBase64String($bytes) -replace '[+/=]', ''
}

$password = New-RandomPassword

# ---- write the password file (git-ignored; never echoed to the console) ----
$mdLines = New-Object System.Collections.Generic.List[string]
$mdLines.Add('# Synthetic test users (backend seed) - DO NOT COMMIT')
$mdLines.Add('')
$mdLines.Add('All 48 role users share one randomly generated password, shown once below. Regenerate by')
$mdLines.Add('re-running backend/tools/make-users.ps1 and re-applying the resulting SQL file.')
$mdLines.Add('')
$mdLines.Add('Password: ' + $password)
$mdLines.Add('')
$mdLines.Add('| role_key | portal | email |')
$mdLines.Add('|---|---|---|')
foreach ($rk in $roles.Keys) {
  $mdLines.Add('| ' + $rk + ' | ' + $roles[$rk] + ' | ' + $rk + '@meridian.test |')
}
$mdPath = Join-Path $seedDir 'test-users.local.md'
Set-Content -Path $mdPath -Value ($mdLines -join "`n") -Encoding utf8

# ---- write the generated SQL (contains the password literal for crypt()) ----
$sqlLines = New-Object System.Collections.Generic.List[string]
$sqlLines.Add('-- Generated by backend/tools/make-users.ps1 - DO NOT COMMIT (contains a password literal).')
$sqlLines.Add('-- One auth.users + auth.identities + app.app_user row per seeded role.')
$sqlLines.Add('do $$')
$sqlLines.Add('declare')
$sqlLines.Add('  v_tenant uuid;')
$sqlLines.Add("  v_pw text := '" + $password + "';")
$sqlLines.Add('  v_uid uuid;')
$sqlLines.Add('begin')
$sqlLines.Add("  select tenant_id into v_tenant from app.tenant where name = 'Meridian Demo Health';")
$sqlLines.Add('')
foreach ($rk in $roles.Keys) {
  $portal = $roles[$rk]
  $email = $rk + '@meridian.test'
  $displayRole = (Get-Culture).TextInfo.ToTitleCase($rk)
  $sqlLines.Add("  if not exists (select 1 from auth.users where email = '" + $email + "') then")
  $sqlLines.Add('    v_uid := app.uuid_v7();')
  $sqlLines.Add("    insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, recovery_token, email_change_token_new, email_change)")
  $sqlLines.Add("      values ('00000000-0000-0000-0000-000000000000', v_uid, 'authenticated', 'authenticated', '" + $email + "', crypt(v_pw, gen_salt('bf')), now(), '{""provider"":""email"",""providers"":[""email""]}'::jsonb, '{}'::jsonb, now(), now(), '', '', '', '');")
  $sqlLines.Add("    insert into auth.identities (id, provider_id, user_id, identity_data, provider, last_sign_in_at, created_at, updated_at)")
  $sqlLines.Add("      values (gen_random_uuid(), v_uid::text, v_uid, jsonb_build_object('sub', v_uid::text, 'email', '" + $email + "'), 'email', now(), now(), now());")
  $sqlLines.Add("    insert into app.app_user (user_id, tenant_id, portal, role_key, party_id, display_name)")
  $sqlLines.Add("      values (v_uid, v_tenant, '" + $portal + "', '" + $rk + "', null, '" + $displayRole + " (test)');")
  $sqlLines.Add('  end if;')
  $sqlLines.Add('')
}
$sqlLines.Add('end $$;')
$sqlPath = Join-Path $seedDir '011_test_users.generated.sql'
Set-Content -Path $sqlPath -Value ($sqlLines -join "`n") -Encoding utf8

Write-Output ("Wrote " + $mdPath + " (password omitted from this output) and " + $sqlPath + ".")
Write-Output ("Apply " + $sqlPath + " against the database, then it (and the .local.md) can be regenerated at will.")
